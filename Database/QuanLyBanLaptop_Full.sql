       SUM(ct.ThanhTien - ct.SoLuong * ct.GiaVon) AS LoiNhuan
FROM HOA_DON hd JOIN CHI_TIET_HD ct ON ct.MaHD = hd.MaHD
GROUP BY YEAR(hd.NgayLap), MONTH(hd.NgayLap);
GO

