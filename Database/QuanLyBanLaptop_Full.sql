SELECT YEAR(hd.NgayLap) AS Nam, MONTH(hd.NgayLap) AS Thang,
       COUNT(DISTINCT hd.MaHD)                   AS SoHoaDon,
       SUM(ct.SoLuong)                           AS SoMayBan,
       SUM(ct.ThanhTien)               AS DoanhThu,
