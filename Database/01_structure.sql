SELECT b.MaPhieuBH,b.SerialNo,s.MaLaptop,COALESCE(b.TenMayNgoai,l.TenLaptop) AS TenLaptop,
 h.MaHD,COALESCE(b.MaKHTiepNhan,h.MaKH) AS MaKH,k.TenKH,k.Sdt,b.MaNV,nv.TenNV,
 b.LoaiDichVu,b.NgayNhan,b.NgayTra,b.MoTaLoi,b.ChiPhi,b.TinhTrangBH,s.NgayHetBH,
 CASE WHEN b.SerialNo IS NOT NULL AND s.NgayHetBH>=CAST(GETDATE() AS date) THEN 1 ELSE 0 END AS ConBaoHanh
FROM dbo.BAO_HANH_SUA_CHUA b
LEFT JOIN dbo.LAPTOP_SERIAL s ON s.SerialNo=b.SerialNo
LEFT JOIN dbo.LAPTOP l ON l.MaLaptop=s.MaLaptop
LEFT JOIN dbo.HOA_DON h ON h.MaHD=s.MaHD
LEFT JOIN dbo.KHACH_HANG k ON k.MaKH=COALESCE(b.MaKHTiepNhan,h.MaKH)
LEFT JOIN dbo.NHAN_VIEN nv ON nv.MaNV=b.MaNV;
GO
